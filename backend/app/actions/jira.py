"""JIRA REST v3 issue payload builder (Atlassian Document Format). DRY_RUN by default."""

from __future__ import annotations

from typing import Any

import httpx

from ..config import get_settings
from ..models import Incident

PRIORITY_MAP = {"P0": "Highest", "P1": "High", "P2": "Medium", "P3": "Low"}


def _para(text: str) -> dict[str, Any]:
    return {"type": "paragraph", "content": [{"type": "text", "text": text}]}


def _heading(text: str) -> dict[str, Any]:
    return {"type": "heading", "attrs": {"level": 3},
            "content": [{"type": "text", "text": text}]}


def _bullets(items: list[str]) -> dict[str, Any]:
    return {
        "type": "bulletList",
        "content": [
            {"type": "listItem", "content": [_para(i)]} for i in items
        ],
    }


def build_payload(incident: Incident, evidence_labels: list[str] | None = None) -> dict[str, Any]:
    cfg = get_settings()
    d = incident.diagnosis
    r = incident.recommendation
    cause = d.primary_cause.label if d else "Under investigation"

    body: list[dict[str, Any]] = [
        _para(
            f"Xperi RevGuard detected a delivery anomaly on {incident.campaign_name} "
            f"({incident.campaign_id}) at {incident.detected_at.strftime('%d %b %Y %H:%M UTC')}."
        ),
        _heading("Business impact"),
        _bullets(
            [
                f"Estimated revenue at risk: ${incident.revenue_risk.expected:,.0f} "
                f"(range ${incident.revenue_risk.conservative:,.0f}–"
                f"${incident.revenue_risk.worst_case:,.0f})",
                f"Impression gap: {incident.revenue_risk.impression_gap:,}",
                f"Health score: {incident.health_score:.0f}/100 · {incident.severity} · "
                f"{incident.priority}",
            ]
        ),
        _heading("Root cause"),
        _para(d.narrative if d else "Diagnosis pending."),
    ]

    if evidence_labels:
        body += [_heading("Evidence"), _bullets(evidence_labels[:8])]

    if r:
        body += [
            _heading("Recommended action"),
            _bullets(
                [
                    r.title,
                    f"Predicted gain: +{r.predicted_impression_gain:,} impressions",
                    f"Estimated recovery: ${r.predicted_recovery.conservative:,.0f}–"
                    f"${r.predicted_recovery.worst_case:,.0f}",
                    f"Confidence: {r.confidence * 100:.0f}%",
                ]
            ),
            _para("Requires human approval before any change is applied to GAM."),
        ]

    body.append(
        _para(
            "Generated by Xperi RevGuard from a simulated dataset. "
            f"Diagnosis engine: {d.generated_by if d else 'n/a'}; "
            f"evidence-grounded: {'yes' if d and d.grounding_passed else 'n/a'}."
        )
    )

    return {
        "fields": {
            "project": {"key": cfg.jira_project_key},
            "issuetype": {"name": "Bug"},
            "summary": f"{incident.campaign_name} underdelivery — {cause}",
            "priority": {"name": PRIORITY_MAP.get(incident.priority, "Medium")},
            "labels": ["revguard", incident.severity.lower(),
                       (d.primary_cause.cause.lower() if d else "undiagnosed")],
            "description": {"type": "doc", "version": 1, "content": body},
        }
    }


def create(incident: Incident, evidence_labels: list[str] | None = None) -> dict[str, Any]:
    cfg = get_settings()
    payload = build_payload(incident, evidence_labels)
    key = f"{cfg.jira_project_key}-{incident.incident_id.split('-')[-1]}"
    if cfg.dry_run or not cfg.jira_base_url:
        return {"dry_run": True, "created": False, "issue_key": key, "payload": payload}
    response = httpx.post(
        f"{cfg.jira_base_url.rstrip('/')}/rest/api/3/issue",
        json=payload,
        auth=(cfg.jira_email, cfg.jira_api_token),
        timeout=15.0,
    )
    return {
        "dry_run": False,
        "created": response.is_success,
        "issue_key": response.json().get("key", key) if response.is_success else key,
        "payload": payload,
    }
